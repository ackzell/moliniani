// Generates `<name>/background.gen.ts` for every built-in background in
// `src/backgrounds/`: a `<Name>BackgroundProps` interface (JSX / `background()`
// config hover docs) and a `<Name>BackgroundSignals` interface (`createMnRef()`
// tween-method hover docs). Both copy the prop `description` strings from the
// sibling `background.ts` config verbatim, so there is exactly one canonical
// source of prose and byte-identical is guaranteed by construction.
//
// Auto-run by the `gen`/`prebuild`/`build`/`test`/`check` scripts in
// `packages/components/package.json`.
//
// The emitted files are formatter- and lint-ignored (see `.prettierignore` and
// the `/* eslint-disable */` header); never edit them by hand — change the
// `description` in the config and re-run `pnpm gen`.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const backgroundsDir = path.resolve(scriptDir, "../src/backgrounds");

function extractObjectLiteral(src, varName) {
  const re = new RegExp(`const\\s+${varName}\\s*=\\s*(\\{)`);
  const m = re.exec(src);
  if (!m) throw new Error(`Could not find "const ${varName} = {" in source`);
  let i = m.index + m[0].length - 1;
  let depth = 0;
  let quote = null;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (quote) {
      if (ch === "\\") i++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch;
    } else if (ch === "{") {
      depth++;
    } else if (ch === "}") {
      depth--;
      if (depth === 0) return src.slice(m.index + m[0].length - 1, i + 1);
    }
  }
  throw new Error(`Unbalanced "{" in "const ${varName} = {", brace never closed`);
}

function validateDescriptions(name, props) {
  for (const [propName, def] of Object.entries(props)) {
    const desc = def.description;
    if (typeof desc !== "string") continue;
    const bad = [];
    if (desc.includes("|")) bad.push("a pipe `|`");
    if (desc.includes("`")) bad.push("a backtick (`)");
    if (desc.includes("\n")) bad.push("a newline");
    if (desc.includes("\r")) bad.push("a carriage return");
    if (desc.includes("*/")) bad.push("the sequence * /");
    if (bad.length > 0) {
      throw new Error(
        `[gen-background-docs] background "${name}" prop "${propName}" description ` +
          `uses ${bad.join(", ")} — the prose is copied into a Markdown remarks ` +
          `table and JSDoc, so it must stay table-safe. Rewrite it and re-run ` +
          `pnpm gen.`,
      );
    }
  }
}

function wrapDoc(text, width = 78) {
  const words = text.split(" ");
  const lines = [];
  let cur = "";
  for (const word of words) {
    if (cur.length + word.length + 1 > width && cur.length > 0) {
      lines.push(cur);
      cur = word;
    } else if (cur.length === 0) {
      cur = word;
    } else {
      cur += " " + word;
    }
  }
  if (cur.length > 0) lines.push(cur);
  return lines;
}

function emitInterfaces(className, props) {
  const pascal = className.replace(/Background$/, "");
  const signalsInterface = `${pascal}BackgroundSignals`;
  const propsInterface = `${pascal}BackgroundProps`;

  const docBlock = (text) => {
    const wrapped = wrapDoc(text);
    const lines = [`  /**`];
    for (const line of wrapped) lines.push(`   * ${line}`);
    lines.push(`   */`);
    return lines;
  };

  const lines = [
    `// AUTOGENERATED by packages/components/scripts/gen-background-docs.mjs.`,
    `// Single source of prose: the \`description\` strings in this directory's`,
    `// background.ts (never edit this file by hand — run \`pnpm gen\`, which the`,
    `// build/test/check scripts also run, after changing a description).`,
    `/* eslint-disable */`,
    ``,
    `import { type NumberSignalMethod, type StringSignalMethod } from "@moliniani/core";`,
    ``,
    `/**`,
    ` * Tween methods exposed by ${className} — one per declarative prop. Hover`,
    ` * docs mirror the config \`description\`s verbatim, so \`createMnRef()\` refs`,
    ` * read the same prose as the JSX attributes.`,
    ` */`,
    `export interface ${signalsInterface} {`,
  ];

  for (const [propName, def] of Object.entries(props)) {
    const methodType = def.type === "color" ? "StringSignalMethod" : "NumberSignalMethod";
    lines.push(...docBlock(def.description ?? `(no description)`));
    lines.push(`  ${propName}: ${methodType};`);
  }

  lines.push(`}`, ``);
  lines.push(`/**`);
  lines.push(
    ` * Declarative props of ${className} (JSX attributes and \`background(...)\``,
    ` * config literals). Carries the per-prop hover docs, mirroring the config`,
    ` * \`description\`s verbatim.`,
    ` */`,
    `export interface ${propsInterface} {`,
  );

  for (const [propName, def] of Object.entries(props)) {
    const valueType = def.type === "color" ? "string" : "number";
    lines.push(...docBlock(def.description ?? `(no description)`));
    lines.push(`  ${propName}?: ${valueType};`);
  }

  lines.push(`}`);
  return lines.join("\n") + "\n";
}

let changed = false;
for (const dir of readdirSync(backgroundsDir, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const backgroundTs = path.join(backgroundsDir, dir.name, "background.ts");

  const src = readFileSync(backgroundTs, "utf8");
  const classMatch = /export const (\w+Background)\s*=\s*define(?:Canvas)?Background</.exec(src);
  if (!classMatch) {
    console.warn(`[gen-background-docs] skip ${dir.name}: no define(Canvas)Background export`);
    continue;
  }
  const className = classMatch[1];
  const propsVarMatch = /typeof\s+(\w+Props)/.exec(src);
  if (!propsVarMatch)
    throw new Error(`[gen-background-docs] ${dir.name}: no "typeof <Props>" generic`);
  const propsVar = propsVarMatch[1];

  const literal = extractObjectLiteral(src, propsVar);
  const props = new Function(`return (${literal})`)();

  validateDescriptions(propsVar, props);

  const outPath = path.join(backgroundsDir, dir.name, "background.gen.ts");
  const next = emitInterfaces(className, props);
  let prev = "";
  try {
    prev = readFileSync(outPath, "utf8");
  } catch {
    prev = "";
  }
  if (prev !== next) writeFileSync(outPath, next);
  changed = true;
  console.log(
    `[gen-background-docs] ${dir.name} -> background.gen.ts (${Object.keys(props).length} props)`,
  );
}

if (!changed) console.log("[gen-background-docs] no backgrounds found to generate");
